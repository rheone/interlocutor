namespace Interlocutor.Generator;

using System;
using System.Collections.Generic;
using System.Text;

/// <summary>
/// Emits the second partial declaration <see cref="OutcomeMemberGenerator"/> adds for one attributed
/// <see cref="OutcomeUnionModel"/>: <c>Match</c>, <c>Switch</c>, per-case <c>TryGetValue</c>, <c>ToString</c>,
/// <c>IsSuccess</c>, and value-based equality (<c>Equals</c>, <c>GetHashCode</c>, <c>IEquatable&lt;TSelf&gt;</c>,
/// <c>==</c>/<c>!=</c>).
/// </summary>
internal static class OutcomeMemberEmitter
{
    /// <summary>Emits the generated partial declaration's full source text for <paramref name="model"/>.</summary>
    /// <param name="model">The attributed union to emit members for. Must have at least two case types.</param>
    /// <returns>The generated C# source.</returns>
    public static string Emit(OutcomeUnionModel model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        var hasNamespace = model.Namespace.Length > 0;
        if (hasNamespace)
        {
            builder.Append("namespace ").Append(model.Namespace).AppendLine(";");
            builder.AppendLine();
        }

        var typeParameterList = model.TypeParameterNames.IsEmpty
            ? string.Empty
            : $"<{string.Join(", ", model.TypeParameterNames)}>";
        var selfType = model.TypeName + typeParameterList;

        builder
            .Append(model.ModifiersText)
            .Append(" union ")
            .Append(model.TypeName)
            .Append(typeParameterList)
            .Append(" : global::System.IEquatable<")
            .Append(selfType)
            .AppendLine(">");
        builder.AppendLine("{");

        EmitIsSuccess(builder, model);
        builder.AppendLine();
        EmitTryGetValueOverloads(builder, model);
        builder.AppendLine();
        EmitMatch(builder, model);
        builder.AppendLine();
        EmitSwitch(builder, model);
        builder.AppendLine();
        EmitToString(builder);
        builder.AppendLine();
        EmitEquality(builder, selfType);

        builder.AppendLine("}");

        return builder.ToString();
    }

    private static void EmitIsSuccess(StringBuilder builder, OutcomeUnionModel model)
    {
        builder
            .Append("    /// <summary>Gets a value indicating whether this result holds the success case, ")
            .Append(model.CaseTypeDisplayStrings[0])
            .AppendLine(".</summary>");
        builder.Append("    public bool IsSuccess => this.Value is ").Append(model.CaseTypeDisplayStrings[0]).AppendLine(";");
    }

    private static void EmitTryGetValueOverloads(StringBuilder builder, OutcomeUnionModel model)
    {
        for (var i = 0; i < model.CaseTypeDisplayStrings.Length; i++)
        {
            var caseType = model.CaseTypeDisplayStrings[i];
            builder
                .Append("    /// <summary>Attempts to read this result's value as its ")
                .Append(caseType)
                .AppendLine(" case.</summary>");
            builder.Append("    public bool TryGetValue(out ").Append(caseType).AppendLine(" value)");
            builder.AppendLine("    {");
            builder.Append("        if (this.Value is ").Append(caseType).AppendLine(" matched)");
            builder.AppendLine("        {");
            builder.AppendLine("            value = matched;");
            builder.AppendLine("            return true;");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        value = default!;");
            builder.AppendLine("        return false;");
            builder.AppendLine("    }");

            if (i < model.CaseTypeDisplayStrings.Length - 1)
            {
                builder.AppendLine();
            }
        }
    }

    private static void EmitMatch(StringBuilder builder, OutcomeUnionModel model)
    {
        builder.AppendLine(
            "    /// <summary>Projects this result to a <typeparamref name=\"TResult\"/> by dispatching to the delegate matching its active case.</summary>"
        );
        builder.Append("    public TResult Match<TResult>(");
        builder.Append(
            string.Join(
                ", ",
                Enumerate(model, static (caseType, i) => $"global::System.Func<{caseType}, TResult> onCase{i + 1}")
            )
        );
        builder.AppendLine(")");
        builder.AppendLine("    {");
        builder.AppendLine("        return this.Value switch");
        builder.AppendLine("        {");
        foreach (
            var line in Enumerate(
                model,
                static (caseType, i) => $"            {caseType} case{i + 1} => onCase{i + 1}(case{i + 1}),"
            )
        )
        {
            builder.AppendLine(line);
        }

        builder.AppendLine(
            "            _ => throw new global::System.InvalidOperationException(\"Outcome holds no recognized case value.\"),"
        );
        builder.AppendLine("        };");
        builder.AppendLine("    }");
    }

    private static void EmitSwitch(StringBuilder builder, OutcomeUnionModel model)
    {
        builder.AppendLine("    /// <summary>Dispatches to the action matching this result's active case.</summary>");
        builder.Append("    public void Switch(");
        builder.Append(
            string.Join(", ", Enumerate(model, static (caseType, i) => $"global::System.Action<{caseType}> onCase{i + 1}"))
        );
        builder.AppendLine(")");
        builder.AppendLine("    {");
        builder.AppendLine("        switch (this.Value)");
        builder.AppendLine("        {");
        foreach (
            var line in Enumerate(
                model,
                static (caseType, i) => $"            case {caseType} case{i + 1}: onCase{i + 1}(case{i + 1}); return;"
            )
        )
        {
            builder.AppendLine(line);
        }

        builder.AppendLine(
            "            default: throw new global::System.InvalidOperationException(\"Outcome holds no recognized case value.\");"
        );
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void EmitToString(StringBuilder builder)
    {
        builder.AppendLine(
            "    /// <summary>Forwards to the active case value's own <see cref=\"object.ToString\"/> override.</summary>"
        );
        builder.AppendLine("    public override string ToString() => this.Value?.ToString() ?? string.Empty;");
    }

    /// <summary>
    /// Emits <c>Equals</c>/<c>GetHashCode</c>/<c>==</c>/<c>!=</c>, all delegating to the boxed <c>Value</c>'s own
    /// equality. Checking <c>obj is </c><paramref name="selfType"/> before delegating means two different case
    /// types boxed into the same union never compare equal by coincidence (each case type is already a
    /// distinctly-typed <c>readonly record struct</c>), and a value boxed into one union arity never equals the
    /// "same" value boxed into a different arity (a different runtime type entirely) - the same way record
    /// equality already behaves.
    /// </summary>
    private static void EmitEquality(StringBuilder builder, string selfType)
    {
        builder.AppendLine(
            "    /// <summary>Determines whether this result and <paramref name=\"other\"/> hold equal case values.</summary>"
        );
        builder
            .Append("    public bool Equals(")
            .Append(selfType)
            .AppendLine(" other) => global::System.Object.Equals(this.Value, other.Value);");
        builder.AppendLine();
        builder.AppendLine(
            "    /// <summary>Determines whether this result and <paramref name=\"obj\"/> hold equal case values.</summary>"
        );
        builder
            .Append("    public override bool Equals(object? obj) => obj is ")
            .Append(selfType)
            .AppendLine(" other && this.Equals(other);");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>Returns a hash code derived from the active case value.</summary>");
        builder.AppendLine("    public override int GetHashCode() => this.Value?.GetHashCode() ?? 0;");
        builder.AppendLine();
        builder.AppendLine(
            "    /// <summary>Determines whether <paramref name=\"left\"/> and <paramref name=\"right\"/> hold equal case values.</summary>"
        );
        builder
            .Append("    public static bool operator ==(")
            .Append(selfType)
            .Append(" left, ")
            .Append(selfType)
            .AppendLine(" right) => left.Equals(right);");
        builder.AppendLine();
        builder.AppendLine(
            "    /// <summary>Determines whether <paramref name=\"left\"/> and <paramref name=\"right\"/> hold unequal case values.</summary>"
        );
        builder
            .Append("    public static bool operator !=(")
            .Append(selfType)
            .Append(" left, ")
            .Append(selfType)
            .AppendLine(" right) => !left.Equals(right);");
    }

    /// <summary>Projects each case type (with its 0-based index) through <paramref name="selector"/>.</summary>
    /// <param name="model">The model whose case types to enumerate.</param>
    /// <param name="selector">Projects one case type's display string and index to an emitted line/fragment.</param>
    private static IEnumerable<string> Enumerate(OutcomeUnionModel model, Func<string, int, string> selector)
    {
        for (var i = 0; i < model.CaseTypeDisplayStrings.Length; i++)
        {
            yield return selector(model.CaseTypeDisplayStrings[i], i);
        }
    }
}
