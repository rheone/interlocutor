namespace Interlocutor.Generator;

using System.Collections.Immutable;
using System.Text;

/// <summary>
/// Emits one closed dispatch wrapper per query, command, or void-command handler discovered in the
/// compilation - the compile-time replacement for the runtime
/// <c>Activator.CreateInstance(typeof(QueryHandlerWrapper&lt;,&gt;).MakeGenericType(requestType, responseType))</c>
/// construction <c>Mediator.Send</c> performs today for a request type seen for the first time.
/// </summary>
/// <remarks>
/// <para>
/// Each wrapper is a self-contained static class - it does not derive from
/// <c>Interlocutor.Abstractions.Core.HandlerWrapper&lt;TResponse&gt;</c> (that type is <c>internal</c> to
/// <c>Interlocutor.Abstractions</c>, so generated code in an arbitrary consuming assembly cannot subclass it
/// without a solution-wide <c>InternalsVisibleTo</c> that would have to name every possible consumer assembly
/// up front). Instead each wrapper reproduces the same behavior-chain composition
/// <c>QueryHandlerWrapper{TQuery,TResponse}.Handle</c> performs - resolve the handler, resolve every
/// <c>IPipelineBehavior&lt;TRequest,TResponse&gt;</c>, fold them around the handler call in reverse
/// registration order - using only compile-time-known closed types and <see cref="System.IServiceProvider.GetService(System.Type)"/>,
/// never a further <c>MakeGenericType</c>/<c>Activator.CreateInstance</c> call.
/// </para>
/// <para>
/// <b>Notification handlers are intentionally not given a dispatch wrapper here.</b> Unlike queries and
/// commands, a notification fans out to every registered handler and does not run through the pipeline
/// behavior chain at all (see <c>INotificationHandler&lt;T&gt;</c>'s remarks) - there is no single "closed
/// wrapper per handler" to emit in the same sense. Notification handlers still get registered (see
/// <see cref="RegistrationModuleEmitter"/>) and are resolved and fanned out exactly as they are today via
/// <c>SequentialNotificationHandlerWrapper&lt;T&gt;</c>/<c>ParallelNotificationHandlerWrapper&lt;T&gt;</c>, which
/// already avoid per-handler reflection - only the per-request-type wrapper *type* construction is what this
/// ticket's dispatch wrappers replace, and that construction never happens for notifications in the first place.
/// </para>
/// </remarks>
internal static class DispatchWrapperEmitter
{
    /// <summary>The namespace every generated dispatch wrapper lives under.</summary>
    public const string GeneratedNamespace = "Interlocutor.Generated.Dispatch";

    /// <summary>
    /// Emits the full source text for every query/command/void-command handler's closed dispatch wrapper.
    /// </summary>
    /// <param name="handlers">Every handler discovered in the compilation.</param>
    /// <returns>Compilable C# source text. Empty of wrapper classes (but still valid) when no handlers dispatch through the pipeline.</returns>
    public static string Emit(ImmutableArray<HandlerModel> handlers)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator - do not edit by hand. See ADR-0008.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {GeneratedNamespace}");
        builder.AppendLine("{");

        foreach (var handler in handlers)
        {
            if (handler.Kind == HandlerKind.Notification)
            {
                continue;
            }

            EmitWrapper(builder, handler);
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>Emits one wrapper class for a query, command, or void-command handler.</summary>
    private static void EmitWrapper(StringBuilder builder, HandlerModel handler)
    {
        var className = $"{IdentifierSanitizer.ToIdentifier(handler.HandlerTypeName)}_{handler.Kind}_Dispatch";
        var requestType = handler.RequestTypeName;
        var responseType = handler.ResponseTypeName!;
        var behaviorType = $"global::Interlocutor.Abstractions.Pipeline.IPipelineBehavior<{requestType}, {responseType}>";

        // Plain, XML-escaped <c> text, not <see cref="...">: these fully-qualified names carry generic
        // arguments (angle brackets and commas), which is neither valid cref syntax nor valid raw XML
        // element content without escaping.
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            $"    /// Closed dispatch wrapper for <c>{XmlEscape(handler.ServiceInterfaceName)}</c>, generated for"
        );
        builder.AppendLine($"    /// <c>{XmlEscape(handler.HandlerTypeName)}</c>.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    internal static class {className}");
        builder.AppendLine("    {");
        builder.AppendLine(
            "        /// <summary>Resolves the handler and applicable behaviors from <paramref name=\"services\"/> and dispatches the request.</summary>"
        );
        builder.AppendLine("        /// <param name=\"request\">The request to dispatch.</param>");
        builder.AppendLine(
            "        /// <param name=\"services\">The service provider to resolve the handler and behaviors from.</param>"
        );
        builder.AppendLine("        /// <param name=\"ct\">A token that may be used to cancel the operation.</param>");
        builder.AppendLine(
            "        /// <returns>The handler's response, after passing through every applicable pipeline behavior.</returns>"
        );
        builder.AppendLine(
            $"        public static async global::System.Threading.Tasks.Task<{responseType}> HandleAsync({requestType} request, global::System.IServiceProvider services, global::System.Threading.CancellationToken ct)"
        );
        builder.AppendLine("        {");
        builder.AppendLine(
            $"            var handler = ({handler.ServiceInterfaceName})(services.GetService(typeof({handler.ServiceInterfaceName}))"
        );
        builder.AppendLine(
            $"                ?? throw new global::System.InvalidOperationException(\"No handler registered for service type '{handler.ServiceInterfaceName}'.\"));"
        );
        builder.AppendLine();
        builder.AppendLine(
            $"            global::System.Func<global::System.Threading.Tasks.Task<{responseType}>> pipeline = () => handler.Handle(request, ct);"
        );
        builder.AppendLine();
        builder.AppendLine(
            $"            var behaviors = (global::System.Collections.Generic.IEnumerable<{behaviorType}>?)services.GetService(typeof(global::System.Collections.Generic.IEnumerable<{behaviorType}>));"
        );
        builder.AppendLine($"            var behaviorList = new global::System.Collections.Generic.List<{behaviorType}>();");
        builder.AppendLine("            if (behaviors is not null)");
        builder.AppendLine("            {");
        builder.AppendLine("                foreach (var behavior in behaviors)");
        builder.AppendLine("                {");
        builder.AppendLine("                    behaviorList.Add(behavior);");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            for (var i = behaviorList.Count - 1; i >= 0; i--)");
        builder.AppendLine("            {");
        builder.AppendLine("                var next = pipeline;");
        builder.AppendLine("                {");
        builder.AppendLine("                    var behavior = behaviorList[i];");
        builder.AppendLine("                    pipeline = () => behavior.Handle(request, next, ct);");
        builder.AppendLine("                }");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine("            return await pipeline().ConfigureAwait(false);");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    /// <summary>Escapes the characters that are illegal as raw content inside an XML doc-comment element.</summary>
    private static string XmlEscape(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
