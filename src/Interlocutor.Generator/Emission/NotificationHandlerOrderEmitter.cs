namespace Interlocutor.Generator.Emission;

using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Interlocutor.Generator.Analysis;

/// <summary>
/// Emits the generated <c>IGeneratedNotificationHandlerOrder</c> implementation carrying
/// <see cref="NotificationHandlerOrderPlanner"/>'s computed ranks (ADR-0007).
/// </summary>
internal static class NotificationHandlerOrderEmitter
{
    /// <summary>The generated order provider type's unqualified name.</summary>
    public const string TypeName = "InterlocutorGeneratedNotificationHandlerOrder";

    /// <summary>Emits the full source text for the generated order provider.</summary>
    /// <param name="ranks">Fully-qualified handler type name to its zero-based topological rank.</param>
    /// <returns>Compilable C# source text.</returns>
    public static string Emit(ImmutableDictionary<string, int> ranks)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator - do not edit by hand. See ADR-0007.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {RegistrationModuleEmitter.GeneratedNamespaceRoot}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Compile-time computed notification handler order (ADR-0007): a rank for every handler type"
        );
        builder.AppendLine(
            "    /// involved in at least one NotificationHandlerRunAfterAttribute/NotificationHandlerRunBeforeAttribute"
        );
        builder.AppendLine("    /// relationship. Every other handler type is unranked.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            $"    internal sealed class {TypeName} : global::Interlocutor.Abstractions.Core.IGeneratedNotificationHandlerOrder"
        );
        builder.AppendLine("    {");
        builder.AppendLine(
            "        private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, int> Ranks = new()"
        );
        builder.AppendLine("        {");
        foreach (var entry in ranks.OrderBy(kv => kv.Value))
        {
            builder.AppendLine($"            [typeof({entry.Key})] = {entry.Value},");
        }

        builder.AppendLine("        };");
        builder.AppendLine();
        builder.AppendLine("        /// <inheritdoc/>");
        builder.AppendLine(
            "        public int Rank(global::System.Type handlerType) => Ranks.TryGetValue(handlerType, out var rank) ? rank : int.MaxValue;"
        );
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }
}
