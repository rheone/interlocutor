namespace Interlocutor.Generator.Emission;

using System.Collections.Immutable;
using System.Text;
using Interlocutor.Generator.Models;

/// <summary>
/// Emits one closed dispatch wrapper per query, command, or bare-command handler discovered in the
/// compilation - the compile-time replacement for the runtime
/// <c>Activator.CreateInstance(typeof(QueryHandlerWrapper&lt;,&gt;).MakeGenericType(requestType, responseType))</c>
/// construction <c>Mediator.SendAsync</c> performs today for a request type seen for the first time.
/// </summary>
/// <remarks>
/// <para>
/// Each wrapper is a self-contained static class - it does not derive from
/// <c>Interlocutor.Abstractions.Core.HandlerWrapper&lt;TResponse&gt;</c> (that type is <c>internal</c> to
/// <c>Interlocutor.Abstractions</c>, so generated code in an arbitrary consuming assembly cannot subclass it
/// without a solution-wide <c>InternalsVisibleTo</c> that would have to name every possible consumer assembly
/// up front). Instead each wrapper resolves the handler from <c>services</c> and hands its bound call to the
/// public <c>Interlocutor.Abstractions.Pipeline.PipelineChainExecutor.ExecuteAsync</c> - the same entry point
/// <c>QueryHandlerWrapper{TQuery,TResponse}.HandleAsync</c> and its siblings call - which resolves the
/// applicable behavior list via <c>PipelineChainResolver.ResolveChain</c> (so a per-request-type pipeline
/// override resolves identically on both dispatch paths) and folds it around the handler call, using only
/// compile-time-known closed types, never a <c>MakeGenericType</c>/<c>Activator.CreateInstance</c> call. This
/// wrapper does not re-derive that fold or its eject-catch guards itself - see
/// <c>PipelineChainExecutor.ExecuteAsync</c>'s remarks for why both dispatch paths now share one
/// implementation.
/// </para>
/// <para>
/// <b>Notification handlers are intentionally not given a dispatch wrapper here.</b> Unlike queries and
/// commands, a notification fans out to every registered handler and does not run through the pipeline
/// behavior chain at all (see <c>INotificationHandler&lt;T&gt;</c>'s remarks) - there is no single "closed
/// wrapper per handler" to emit in the same sense. Notification handlers still get registered (see
/// <see cref="RegistrationModuleEmitter"/>) and are resolved and fanned out exactly as they are today via
/// <c>SequentialNotificationHandlerWrapper&lt;T&gt;</c>/<c>ParallelNotificationHandlerWrapper&lt;T&gt;</c>, which
/// already avoid per-handler reflection - only the per-request-type wrapper *type* construction is what this
/// ticket's dispatch wrappers replace, and that construction never happens for notifications in the first place.
/// </para>
/// </remarks>
internal static class DispatchWrapperEmitter
{
    /// <summary>The namespace every generated dispatch wrapper lives under.</summary>
    public const string GeneratedNamespace = "Interlocutor.Generated.Dispatch";

    /// <summary>
    /// Emits the full source text for every query/command/bare-command handler's closed dispatch wrapper.
    /// </summary>
    /// <param name="handlers">Every handler discovered in the compilation.</param>
    /// <returns>Compilable C# source text. Empty of wrapper classes (but still valid) when no handlers dispatch through the pipeline.</returns>
    public static string Emit(ImmutableArray<HandlerModel> handlers)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator - do not edit by hand. See ADR-0008.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {GeneratedNamespace}");
        builder.AppendLine("{");

        foreach (var handler in handlers)
        {
            if (handler.Kind == HandlerKind.Notification)
            {
                continue;
            }

            EmitWrapper(builder, handler);
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>
    /// Builds the unqualified class name <see cref="Emit"/> gives <paramref name="handler"/>'s wrapper - shared
    /// with <see cref="RequestDispatchSwitchEmitter"/> so the generated type switch can call the exact same
    /// wrapper class this emitter produces, without either emitter re-deriving the other's naming scheme.
    /// </summary>
    /// <param name="handler">The handler to name a wrapper class for.</param>
    /// <returns>The wrapper class's unqualified name, unique within <see cref="GeneratedNamespace"/>.</returns>
    public static string GetWrapperClassName(HandlerModel handler) =>
        $"{IdentifierSanitizer.ToIdentifier(handler.HandlerTypeName)}_{handler.Kind}_Dispatch";

    /// <summary>Emits one wrapper class for a query, command, or bare-command handler.</summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="handler">The handler to emit a dispatch wrapper for.</param>
    private static void EmitWrapper(StringBuilder builder, HandlerModel handler)
    {
        var className = GetWrapperClassName(handler);
        var requestType = handler.RequestTypeName;
        var responseType = handler.ResponseTypeName!;

        // Plain, XML-escaped <c> text, not <see cref="...">: these fully-qualified names carry generic
        // arguments (angle brackets and commas), which is neither valid cref syntax nor valid raw XML
        // element content without escaping.
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            $"    /// Closed dispatch wrapper for <c>{XmlEscape(handler.ServiceInterfaceName)}</c>, generated for"
        );
        builder.AppendLine($"    /// <c>{XmlEscape(handler.HandlerTypeName)}</c>.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    internal static class {className}");
        builder.AppendLine("    {");
        builder.AppendLine(
            "        /// <summary>Resolves the handler and applicable behaviors from <paramref name=\"services\"/> and dispatches the request.</summary>"
        );
        builder.AppendLine("        /// <param name=\"request\">The request to dispatch.</param>");
        builder.AppendLine(
            "        /// <param name=\"services\">The service provider to resolve the handler and behaviors from.</param>"
        );
        builder.AppendLine("        /// <param name=\"ct\">A token that may be used to cancel the operation.</param>");
        builder.AppendLine(
            "        /// <returns>The handler's response, after passing through every applicable pipeline behavior.</returns>"
        );
        builder.AppendLine(
            $"        public static global::System.Threading.Tasks.Task<{responseType}> HandleAsync({requestType} request, global::System.IServiceProvider services, global::System.Threading.CancellationToken ct)"
        );
        builder.AppendLine("        {");
        builder.AppendLine(
            $"            var handler = ({handler.ServiceInterfaceName})(services.GetService(typeof({handler.ServiceInterfaceName}))"
        );
        builder.AppendLine(
            $"                ?? throw new global::System.InvalidOperationException(\"No handler registered for service type '{handler.ServiceInterfaceName}'.\"));"
        );
        builder.AppendLine();

        // Delegates the fold-and-eject-catch logic entirely to the same PipelineChainExecutor.ExecuteAsync
        // the hand-written wrappers (QueryHandlerWrapper/CommandHandlerWrapper/BareCommandHandlerWrapper) call
        // - see that method's remarks. This wrapper's only remaining job is resolving the handler above and
        // handing its bound call over as the innermost pipeline delegate; PipelineChainExecutor composes the
        // behavior chain around it and catches both PipelineEjectException<TResponse> and
        // PipelineEjectCaseException at every layer, so a request ejected via Eject.With/Eject.WithCase
        // recovers here exactly as it does on the hand-written path - one algorithm, not two kept in sync by
        // hand. This static wrapper has no Activity parameter of its own (adding one would be a breaking
        // change to the public IGeneratedRequestDispatcher contract), so it passes
        // System.Diagnostics.Activity.Current, which Mediator's dispatch already keeps current for the whole
        // nested call (see Mediator.SendAsync(object, CancellationToken)'s remarks on nested-activity parenting).
        builder.AppendLine(
            $"            return global::Interlocutor.Abstractions.Pipeline.PipelineChainExecutor.ExecuteAsync<{requestType}, {responseType}>("
        );
        builder.AppendLine("                request,");
        builder.AppendLine("                handler.HandleAsync,");
        builder.AppendLine("                services,");
        builder.AppendLine("                ct,");
        builder.AppendLine("                global::System.Diagnostics.Activity.Current);");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    /// <summary>Escapes the characters that are illegal as raw content inside an XML doc-comment element.</summary>
    /// <param name="value">The text to escape.</param>
    /// <returns><paramref name="value"/> with <c>&amp;</c>, <c>&lt;</c>, and <c>&gt;</c> replaced by their XML entity equivalents.</returns>
    private static string XmlEscape(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
