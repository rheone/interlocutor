namespace Interlocutor.Generator.Emission;

using System.Collections.Generic;
using System.Linq;
using System.Text;
using Interlocutor.Generator.Models;

/// <summary>
/// Emits the second partial declaration <see cref="ResultExtensionsGenerator"/> adds for the attributed
/// <see cref="ResultExtensionsTargetModel"/>: the <c>ToActionResult</c>/<c>ToMinimalApiResult</c> extension
/// members for the non-generic <c>Outcome</c> and every <c>Outcome&lt;T1, ...&gt;</c> case-arity from
/// <see cref="MinCaseArity"/> through <see cref="MaxCaseArity"/> - the boilerplate that used to be
/// hand-written <c>extension</c> blocks, one per arity. The reflective catch-all overload (constrained to
/// <c>IOutcome</c> alone, for a hand-rolled response type) and the private <c>OutcomeHttpMapping</c> rendering
/// helpers stay hand-written in the other partial declaration.
/// </summary>
/// <remarks>
/// Every emitted arity's <c>Match</c> arms resolve status codes through the same shared, hand-written
/// <c>Classify*</c> helpers (see <see cref="EmitArityExtension"/>'s own remarks) - raising
/// <see cref="MaxCaseArity"/> adds more calls into that same shared logic, never a new copy of it. Raising it
/// further, past the shipped <c>Outcome</c> family's own ceiling, means raising that family's ceiling first -
/// nothing else in this file, and nothing in the hand-written partial, changes either way.
/// </remarks>
internal static class ResultExtensionsEmitter
{
    /// <summary>The lowest case arity emitted - a two-case <c>Outcome&lt;T1, T2&gt;</c>.</summary>
    private const int MinCaseArity = 2;

    /// <summary>
    /// The highest case arity emitted, matching the shipped <c>Outcome</c> union family's own ceiling - the
    /// BCL's widest <c>System.Func&lt;T1..T16, TResult&gt;</c>/<c>System.Action&lt;T1..T16&gt;</c> overload
    /// (see <c>Interlocutor.CommonKernel.Outcome{T1,...,T16}</c>'s own remarks).
    /// </summary>
    private const int MaxCaseArity = 16;

    /// <summary>Emits the generated partial declaration's full source text for <paramref name="model"/>.</summary>
    /// <param name="model">The attributed target class to emit the HTTP result overloads onto.</param>
    /// <returns>The generated C# source.</returns>
    public static string Emit(ResultExtensionsTargetModel model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        // RS0026 ("do not add multiple overloads with optional parameters") flags every ToActionResult/
        // ToMinimalApiResult pair below against its siblings once they move into their own partial declaration
        // - Microsoft.CodeAnalysis.PublicApiAnalyzers 5.6.0 (this repo's pinned version) evidently tracks a C#
        // 14 extension block's members per declaring partial rather than merging by simple name across the
        // whole type, since the identical overload set never triggered it while hand-written in one file
        // alongside the TResponse-constrained catch-all overload. Suppressed here rather than left to trip CI:
        // the arity overloads were already an intentional, pre-existing multiple-overloads-with-optional-
        // parameters shape (see ResultExtensions's own remarks), not a new API design the analyzer's real
        // backcompat concern applies to.
        builder.AppendLine("#pragma warning disable RS0026");
        builder.AppendLine();

        var hasNamespace = model.Namespace.Length > 0;
        if (hasNamespace)
        {
            builder.Append("namespace ").Append(model.Namespace).AppendLine(";");
            builder.AppendLine();
        }

        builder.Append(model.ModifiersText).Append(" class ").Append(model.TypeName).AppendLine();
        builder.AppendLine("{");

        EmitVoidOutcomeExtension(builder);
        for (var arity = MinCaseArity; arity <= MaxCaseArity; arity++)
        {
            builder.AppendLine();
            EmitArityExtension(builder, arity);
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>
    /// Emits the <c>extension(Outcome result)</c> block for the non-generic, case-less acknowledgment. Unlike
    /// every generic arity below, there is no failure case to map - holding a <c>result</c> instance is itself
    /// the acknowledgment (see <c>Outcome</c>'s own remarks) - so both members always render 204/<c>NoContent</c>
    /// unconditionally, and neither takes an <c>IOutcomeStatusMapper</c> parameter: there is nothing for one to
    /// map.
    /// </summary>
    private static void EmitVoidOutcomeExtension(StringBuilder builder)
    {
        builder.AppendLine("    extension(global::Interlocutor.CommonKernel.Outcome result)");
        builder.AppendLine("    {");
        builder.AppendLine("        public global::Microsoft.AspNetCore.Mvc.IActionResult ToActionResult() =>");
        builder.AppendLine("            new global::Microsoft.AspNetCore.Mvc.NoContentResult();");
        builder.AppendLine();
        builder.AppendLine("        public global::Microsoft.AspNetCore.Http.IResult ToMinimalApiResult() =>");
        builder.AppendLine("            global::Microsoft.AspNetCore.Http.Results.NoContent();");
        builder.AppendLine("    }");
    }

    /// <summary>
    /// Emits the <c>extension&lt;T1, ...&gt;(Outcome&lt;T1, ...&gt; result)</c> block for one
    /// case-arity. Both members delegate every case's classification to the shared, hand-written
    /// <c>Classify*</c> helpers on <c>ResultExtensions</c>'s other partial declaration - the active case's
    /// runtime type decides its HTTP status there, not which arm of this <c>Match</c> call happened to fire (see
    /// that partial's own remarks for why the success-slot arm still needs its own type check rather than being
    /// an unconditional 200).
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="arity">The union's case count (success case plus every alternative case).</param>
    private static void EmitArityExtension(StringBuilder builder, int arity)
    {
        var typeParameterNames = CaseTypeParameterNames(arity);
        var valueParameterNames = CaseValueParameterNames(arity);
        var typeParameterList = string.Join(", ", typeParameterNames);
        var outcomeType = $"global::Interlocutor.CommonKernel.Outcome<{typeParameterList}>";

        builder.Append("    extension<").Append(typeParameterList).Append(">(").Append(outcomeType).AppendLine(" result)");
        builder.AppendLine("    {");

        builder.AppendLine(
            "        public global::Microsoft.AspNetCore.Mvc.IActionResult ToActionResult(global::Interlocutor.AspNetCore.IOutcomeStatusMapper? mapper = null) =>"
        );
        builder.AppendLine("            result.Match<global::Microsoft.AspNetCore.Mvc.IActionResult>(");
        builder
            .Append("                ")
            .Append(valueParameterNames[0])
            .Append(" => ClassifySuccessCaseForActionResult(")
            .Append(valueParameterNames[0])
            .AppendLine(", mapper),");
        EmitFailureMatchArms(builder, valueParameterNames, outcomeType, "ClassifyFailureCaseForActionResult");
        builder.AppendLine("            );");
        builder.AppendLine();

        builder.AppendLine(
            "        public global::Microsoft.AspNetCore.Http.IResult ToMinimalApiResult(global::Interlocutor.AspNetCore.IOutcomeStatusMapper? mapper = null) =>"
        );
        builder.AppendLine("            result.Match<global::Microsoft.AspNetCore.Http.IResult>(");
        builder
            .Append("                ")
            .Append(valueParameterNames[0])
            .Append(" => ClassifySuccessCaseForMinimalApiResult(")
            .Append(valueParameterNames[0])
            .AppendLine(", mapper),");
        EmitFailureMatchArms(builder, valueParameterNames, outcomeType, "ClassifyFailureCaseForMinimalApiResult");
        builder.AppendLine("            );");

        builder.AppendLine("    }");
    }

    /// <summary>
    /// Emits one <c>caseN => &lt;classifyMethod&gt;(caseN, mapper, typeof(&lt;outcomeType&gt;))</c> match arm per
    /// failure case (every entry in <paramref name="valueParameterNames"/> after the success case), the last
    /// with no trailing comma.
    /// </summary>
    private static void EmitFailureMatchArms(
        StringBuilder builder,
        IReadOnlyList<string> valueParameterNames,
        string outcomeType,
        string classifyMethod
    )
    {
        for (var i = 1; i < valueParameterNames.Count; i++)
        {
            var isLast = i == valueParameterNames.Count - 1;
            builder
                .Append("                ")
                .Append(valueParameterNames[i])
                .Append(" => ")
                .Append(classifyMethod)
                .Append('(')
                .Append(valueParameterNames[i])
                .Append(", mapper, typeof(")
                .Append(outcomeType)
                .Append("))")
                .AppendLine(isLast ? string.Empty : ",");
        }
    }

    /// <summary>
    /// The type parameter names for one arity, matching the shipped <c>Outcome&lt;T1, ..., TN&gt;</c> family's
    /// own fully symmetric naming: <c>T1, T2, ..., TN</c> - no case position implies a privileged role.
    /// </summary>
    private static string[] CaseTypeParameterNames(int arity) => [.. Enumerable.Range(1, arity).Select(static i => $"T{i}")];

    /// <summary>
    /// The <c>Match</c> lambda parameter names for one arity: <c>ok, failure</c> for arity 2, <c>ok, case2,
    /// case3, ...</c> above that - mirroring <see cref="CaseTypeParameterNames"/>.
    /// </summary>
    private static string[] CaseValueParameterNames(int arity) =>
        arity == 2 ? ["ok", "failure"] : ["ok", .. Enumerable.Range(2, arity - 1).Select(static i => $"case{i}")];
}
