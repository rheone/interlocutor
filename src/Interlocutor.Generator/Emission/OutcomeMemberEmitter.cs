namespace Interlocutor.Generator.Emission;

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Interlocutor.Generator.Models;

/// <summary>
/// Emits the second partial declaration <see cref="OutcomeMemberGenerator"/> adds for one attributed
/// <see cref="OutcomeUnionModel"/>: unconditionally, a per-case static <c>Create</c> factory overload,
/// <c>Match</c>, <c>Switch</c>, per-case anonymous <c>TryGetValue</c> (plus a named <c>TryGet{TypeName}</c>
/// counterpart for every concrete case type - see <see cref="OutcomeUnionModel.CaseAccessorNames"/>),
/// <c>ToString</c>, and value-based equality (<c>Equals</c>, <c>GetHashCode</c>, <c>IEquatable&lt;TSelf&gt;</c>,
/// <c>==</c>/<c>!=</c>); additionally, <c>IOutcomeCase</c> and <c>ActiveCaseType</c> when
/// <see cref="OutcomeUnionModel.ImplementsIOutcome"/> is <see langword="true"/>.
/// </summary>
internal static class OutcomeMemberEmitter
{
    /// <summary>Gets every generated member name this emitter can ever introduce onto a union's declaration.</summary>
    /// <value>
    /// Computed once so <see cref="Analysis.OutcomeAccessorCollisionAnalyzer"/> can read a single source of
    /// truth instead of hand-declaring its own copy that would otherwise have to be kept in sync by hand.
    /// Includes <c>ActiveCaseType</c> unconditionally, even though this emitter only actually writes it
    /// when <see cref="OutcomeUnionModel.ImplementsIOutcome"/> is <see langword="true"/> - reserving the
    /// name regardless keeps the check simple and costs nothing, since it isn't a plausible case type
    /// identifier to give up. Also includes <c>Value</c>, the compiler-synthesized boxed field every
    /// <c>union</c> type carries (see <see cref="EmitGetActiveCaseIndex"/>'s remarks) - this emitter relies
    /// on it via <c>this.Value</c> but never declares it itself, so it would otherwise be invisible to a
    /// set built purely from what <see cref="Emit"/> writes. Includes <c>Create</c>, the discoverable static
    /// factory <see cref="EmitFactories"/> overloads once per case type - the same "fixed name, overloaded
    /// per case" shape <c>TryGetValue</c> already has, so it belongs in this set for the identical reason.
    /// </value>
    public static ImmutableArray<string> ReservedMemberNames { get; } =
        ImmutableArray.Create(
            "Value",
            "ActiveCaseType",
            "TryGetValue",
            "Match",
            "Switch",
            "ToString",
            "Equals",
            "GetHashCode",
            "Create"
        );

    /// <summary>Emits the generated partial declaration's full source text for <paramref name="model"/>.</summary>
    /// <param name="model">The attributed union to emit members for. Must have at least two case types.</param>
    /// <returns>The generated C# source.</returns>
    public static string Emit(OutcomeUnionModel model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        var hasNamespace = model.Namespace.Length > 0;
        if (hasNamespace)
        {
            builder.Append("namespace ").Append(model.Namespace).AppendLine(";");
            builder.AppendLine();
        }

        var typeParameterList = model.TypeParameterNames.IsEmpty
            ? string.Empty
            : $"<{string.Join(", ", model.TypeParameterNames)}>";
        var selfType = model.TypeName + typeParameterList;

        builder.Append(model.ModifiersText).Append(" union ").Append(model.TypeName).Append(typeParameterList);
        builder.Append(" : global::System.IEquatable<").Append(selfType).Append('>');
        if (model.ImplementsIOutcome)
        {
            // Only a union that opted into the classification surface (declared `: IOutcome`) implements
            // IOutcomeCase - see OutcomeUnionModel.ImplementsIOutcome's remarks for why this is opt-in rather
            // than unconditional.
            builder.Append(", global::Interlocutor.CommonKernel.ResultTypes.IOutcomeCase");
        }

        builder.AppendLine();
        builder.AppendLine("{");

        EmitGetActiveCaseIndex(builder, model);
        builder.AppendLine();
        if (model.ImplementsIOutcome)
        {
            EmitActiveCaseType(builder, model);
            builder.AppendLine();
        }

        EmitFactories(builder, model, selfType);
        builder.AppendLine();
        EmitTryGetValueOverloads(builder, model);
        builder.AppendLine();
        EmitMatch(builder, model);
        builder.AppendLine();
        EmitSwitch(builder, model);
        builder.AppendLine();
        EmitToString(builder);
        builder.AppendLine();
        EmitEquality(builder, selfType);

        builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>
    /// Emits the private helper every other generated member consults to learn which case is active. A
    /// <c>union</c> type may declare no instance fields beyond the compiler-synthesized boxed
    /// <c>object? Value</c>, so there is nowhere to store a discriminator distinguishing "case N was
    /// constructed with a null value" from "no case was ever constructed" - both leave <c>Value</c> null.
    /// This helper resolves that ambiguity without extra storage: a non-null <c>Value</c> still identifies its
    /// case by a type-pattern match (unambiguous, since each case type is distinctly typed), and a null
    /// <c>Value</c> is attributed to the first-declared case type whose own default value is null (a nullable
    /// reference type, or a <see cref="Nullable{T}"/>) - the only case type(s) a null <c>Value</c> could
    /// legitimately have come from. Only when no declared case type accepts null does a null <c>Value</c> mean
    /// what it always meant: the union was never assigned a case.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="model">The union whose case types to emit one type-pattern arm per.</param>
    private static void EmitGetActiveCaseIndex(StringBuilder builder, OutcomeUnionModel model)
    {
        builder.AppendLine(
            "    /// <summary>Resolves the 1-based index of the active case, or 0 if no case was ever set.</summary>"
        );
        builder.AppendLine("    private int GetActiveCaseIndex()");
        builder.AppendLine("    {");
        foreach (var line in Enumerate(model, static (caseType, i) => $"        if (this.Value is {caseType}) return {i + 1};"))
        {
            builder.AppendLine(line);
        }

        builder.AppendLine();
        builder.AppendLine("        if (this.Value is null)");
        builder.AppendLine("        {");
        foreach (
            var line in Enumerate(
                model,
                // Cast through object before the null pattern: a concrete, statically non-nullable case type
                // (e.g. a plain readonly record struct) makes "default(T) is null" a compile error (CS0037),
                // not just always-false, since null isn't a valid literal for that type. Boxing first makes the
                // check legal for every case type - concrete or generic, value or reference - while still
                // evaluating to true only for a nullable reference type or an empty Nullable<T>.
                static (caseType, i) => $"            if ((object?)default({caseType}) is null) return {i + 1};"
            )
        )
        {
            builder.AppendLine(line);
        }

        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return 0;");
        builder.AppendLine("    }");
    }

    /// <summary>
    /// Emits the generated <c>ActiveCaseType</c> property that satisfies <c>IOutcomeCase</c> - one switch arm per
    /// case type, keyed to the same 1-based index <see cref="EmitGetActiveCaseIndex"/> computes, so the two stay
    /// in lockstep without either duplicating the other's indexing.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="model">The union whose case types to emit one <c>typeof(...)</c> arm per.</param>
    private static void EmitActiveCaseType(StringBuilder builder, OutcomeUnionModel model)
    {
        builder.AppendLine(
            "    /// <summary>Gets the active case's declared type, or <see langword=\"null\"/> if no case was ever set.</summary>"
        );
        builder.AppendLine("    public global::System.Type? ActiveCaseType => this.GetActiveCaseIndex() switch");
        builder.AppendLine("    {");
        foreach (var line in Enumerate(model, static (caseType, i) => $"        {i + 1} => typeof({caseType}),"))
        {
            builder.AppendLine(line);
        }

        builder.AppendLine("        _ => null,");
        builder.AppendLine("    };");
    }

    /// <summary>
    /// Emits one static <c>Create</c> overload per case type - a discoverable alternative to the
    /// compiler-generated positional constructor/implicit conversion the <c>union</c> language feature already
    /// provides for the same case value. Overloaded on <paramref name="model"/>'s case types the same way the
    /// compiler's own generated constructors already are, so it introduces no new signature shape; it only adds
    /// a name a caller can find via member-list discovery (constructors don't appear there under the union's own
    /// name the way a static factory does).
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="model">The union whose case types to emit one <c>Create</c> overload per, in declaration order.</param>
    /// <param name="selfType">The union's own closed type name (with type arguments, if generic), as emitted C# text.</param>
    private static void EmitFactories(StringBuilder builder, OutcomeUnionModel model, string selfType)
    {
        // Doc text below never interpolates model.CaseTypeDisplayStrings or selfType directly: either can be a
        // closed generic display string (e.g. "T1, T2, ..." for the type parameter list, or a concrete type
        // argument like "List<string>"), and embedding raw "<"/">"/"," in an XML doc comment's text produces
        // malformed XML (CS1570) rather than the angle brackets a reader would expect.
        for (var i = 0; i < model.CaseTypeDisplayStrings.Length; i++)
        {
            var caseType = model.CaseTypeDisplayStrings[i];

            builder.AppendLine("    /// <summary>Creates a new instance whose active case is this value.</summary>");
            builder.AppendLine("    /// <param name=\"value\">The case value the new instance carries.</param>");
            builder.AppendLine("    /// <returns>A new instance whose active case is <paramref name=\"value\"/>.</returns>");
            builder
                .Append("    public static ")
                .Append(selfType)
                .Append(" Create(")
                .Append(caseType)
                .AppendLine(" value) => value;");

            if (i < model.CaseTypeDisplayStrings.Length - 1)
            {
                builder.AppendLine();
            }
        }
    }

    /// <summary>
    /// Emits every case type's anonymous <c>TryGetValue</c> overload and, for a concrete case type, its named
    /// <c>TryGet{TypeName}</c> counterpart - see <see cref="EmitTryGetAccessorBody"/> for the shared body both
    /// accessors share.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="model">The union whose case types to emit accessors for.</param>
    private static void EmitTryGetValueOverloads(StringBuilder builder, OutcomeUnionModel model)
    {
        for (var i = 0; i < model.CaseTypeDisplayStrings.Length; i++)
        {
            var caseType = model.CaseTypeDisplayStrings[i];
            var caseIndex = i + 1;

            builder
                .Append("    /// <summary>Attempts to read this result's value as its ")
                .Append(caseType)
                .AppendLine(" case.</summary>");
            EmitTryGetAccessorBody(builder, "TryGetValue", caseType, caseIndex);

            // A concrete case type additionally gets a named accessor - see
            // OutcomeUnionModel.CaseAccessorNames' remarks for why a type-parameter case (null here) doesn't.
            var accessorName = model.CaseAccessorNames[i];
            if (accessorName is not null)
            {
                builder.AppendLine();
                builder
                    .Append("    /// <summary>Attempts to read this result's value as its ")
                    .Append(caseType)
                    .AppendLine(" case.</summary>");
                EmitTryGetAccessorBody(builder, "TryGet" + accessorName, caseType, caseIndex);
            }

            if (i < model.CaseTypeDisplayStrings.Length - 1)
            {
                builder.AppendLine();
            }
        }
    }

    /// <summary>
    /// Emits one <c>TryGetValue</c>/named-accessor method body: <see langword="true"/> and
    /// <paramref name="caseType"/>'s value when <paramref name="caseIndex"/> is the active case,
    /// <see langword="false"/> and <c>default</c> otherwise. Shared by <see cref="EmitTryGetValueOverloads"/>'s
    /// anonymous and named accessor for the same case, which differ only in method name.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="methodName">The accessor method's name - <c>TryGetValue</c> or <c>TryGet{TypeName}</c>.</param>
    /// <param name="caseType">The case type this accessor reads, as emitted C# text.</param>
    /// <param name="caseIndex">The case type's 1-based index, matching <see cref="EmitGetActiveCaseIndex"/>'s numbering.</param>
    private static void EmitTryGetAccessorBody(StringBuilder builder, string methodName, string caseType, int caseIndex)
    {
        builder.Append("    public bool ").Append(methodName).Append("(out ").Append(caseType).AppendLine(" value)");
        builder.AppendLine("    {");
        builder.Append("        if (this.GetActiveCaseIndex() == ").Append(caseIndex).AppendLine(")");
        builder.AppendLine("        {");
        builder.Append("            value = (").Append(caseType).AppendLine(")this.Value!;");
        builder.AppendLine("            return true;");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        value = default!;");
        builder.AppendLine("        return false;");
        builder.AppendLine("    }");
    }

    /// <summary>
    /// Emits the generated <c>Match&lt;TResult&gt;</c> method: one <c>Func&lt;TCase, TResult&gt;</c> parameter per
    /// declared case type, in declaration order, dispatched by <see cref="EmitGetActiveCaseIndex"/>'s active-case
    /// index - the delegate positionally paired with the active case's declared type runs, regardless of where
    /// that case type sits in the case list.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="model">The union whose case types to emit one <c>onCaseN</c> parameter per.</param>
    private static void EmitMatch(StringBuilder builder, OutcomeUnionModel model)
    {
        builder.AppendLine(
            "    /// <summary>Projects this result to a <typeparamref name=\"TResult\"/> by dispatching to the delegate matching its active case.</summary>"
        );
        builder.Append("    public TResult Match<TResult>(");
        builder.Append(
            string.Join(
                ", ",
                Enumerate(model, static (caseType, i) => $"global::System.Func<{caseType}, TResult> onCase{i + 1}")
            )
        );
        builder.AppendLine(")");
        builder.AppendLine("    {");
        builder.AppendLine("        return this.GetActiveCaseIndex() switch");
        builder.AppendLine("        {");
        foreach (
            var line in Enumerate(
                model,
                static (caseType, i) => $"            {i + 1} => onCase{i + 1}(({caseType})this.Value!),"
            )
        )
        {
            builder.AppendLine(line);
        }

        builder.AppendLine(
            "            _ => throw new global::System.InvalidOperationException(\"Outcome holds no recognized case value.\"),"
        );
        builder.AppendLine("        };");
        builder.AppendLine("    }");
    }

    /// <summary>
    /// Emits the generated <c>Switch</c> method - <see cref="EmitMatch"/>'s <see langword="void"/>-returning
    /// twin: one <c>Action&lt;TCase&gt;</c> parameter per declared case type, dispatched the same way.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="model">The union whose case types to emit one <c>onCaseN</c> parameter per.</param>
    private static void EmitSwitch(StringBuilder builder, OutcomeUnionModel model)
    {
        builder.AppendLine("    /// <summary>Dispatches to the action matching this result's active case.</summary>");
        builder.Append("    public void Switch(");
        builder.Append(
            string.Join(", ", Enumerate(model, static (caseType, i) => $"global::System.Action<{caseType}> onCase{i + 1}"))
        );
        builder.AppendLine(")");
        builder.AppendLine("    {");
        builder.AppendLine("        switch (this.GetActiveCaseIndex())");
        builder.AppendLine("        {");
        foreach (
            var line in Enumerate(
                model,
                static (caseType, i) => $"            case {i + 1}: onCase{i + 1}(({caseType})this.Value!); return;"
            )
        )
        {
            builder.AppendLine(line);
        }

        builder.AppendLine(
            "            default: throw new global::System.InvalidOperationException(\"Outcome holds no recognized case value.\");"
        );
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    /// <summary>Emits the generated <c>ToString</c> override.</summary>
    /// <param name="builder">The source being built.</param>
    private static void EmitToString(StringBuilder builder)
    {
        builder.AppendLine(
            "    /// <summary>Forwards to the active case value's own <see cref=\"object.ToString\"/> override.</summary>"
        );
        builder.AppendLine("    public override string ToString() => this.Value?.ToString() ?? string.Empty;");
    }

    /// <summary>
    /// Emits <c>Equals</c>/<c>GetHashCode</c>/<c>==</c>/<c>!=</c>, all delegating to the boxed <c>Value</c>'s own
    /// equality. Checking <c>obj is </c><paramref name="selfType"/> before delegating means two different case
    /// types boxed into the same union never compare equal by coincidence (each case type is already a
    /// distinctly-typed <c>readonly record struct</c>), and a value boxed into one union arity never equals the
    /// "same" value boxed into a different arity (a different runtime type entirely) - the same way record
    /// equality already behaves.
    /// </summary>
    /// <param name="builder">The source being built.</param>
    /// <param name="selfType">The union's own closed type name (with type arguments, if generic), as emitted C# text.</param>
    private static void EmitEquality(StringBuilder builder, string selfType)
    {
        builder.AppendLine(
            "    /// <summary>Determines whether this result and <paramref name=\"other\"/> hold equal case values.</summary>"
        );
        builder
            .Append("    public bool Equals(")
            .Append(selfType)
            .AppendLine(" other) => global::System.Object.Equals(this.Value, other.Value);");
        builder.AppendLine();
        builder.AppendLine(
            "    /// <summary>Determines whether this result and <paramref name=\"obj\"/> hold equal case values.</summary>"
        );
        builder
            .Append("    public override bool Equals(object? obj) => obj is ")
            .Append(selfType)
            .AppendLine(" other && this.Equals(other);");
        builder.AppendLine();
        builder.AppendLine("    /// <summary>Returns a hash code derived from the active case value.</summary>");
        builder.AppendLine("    public override int GetHashCode() => this.Value?.GetHashCode() ?? 0;");
        builder.AppendLine();
        builder.AppendLine(
            "    /// <summary>Determines whether <paramref name=\"left\"/> and <paramref name=\"right\"/> hold equal case values.</summary>"
        );
        builder
            .Append("    public static bool operator ==(")
            .Append(selfType)
            .Append(" left, ")
            .Append(selfType)
            .AppendLine(" right) => left.Equals(right);");
        builder.AppendLine();
        builder.AppendLine(
            "    /// <summary>Determines whether <paramref name=\"left\"/> and <paramref name=\"right\"/> hold unequal case values.</summary>"
        );
        builder
            .Append("    public static bool operator !=(")
            .Append(selfType)
            .Append(" left, ")
            .Append(selfType)
            .AppendLine(" right) => !left.Equals(right);");
    }

    /// <summary>Projects each case type (with its 0-based index) through <paramref name="selector"/>.</summary>
    /// <param name="model">The model whose case types to enumerate.</param>
    /// <param name="selector">Projects one case type's display string and index to an emitted line/fragment.</param>
    private static IEnumerable<string> Enumerate(OutcomeUnionModel model, Func<string, int, string> selector)
    {
        for (var i = 0; i < model.CaseTypeDisplayStrings.Length; i++)
        {
            yield return selector(model.CaseTypeDisplayStrings[i], i);
        }
    }
}
