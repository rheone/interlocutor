namespace Interlocutor.Generator.Emission;

using System.Collections.Immutable;
using System.Text;
using Interlocutor.Generator.Models;

/// <summary>
/// Emits the compile-time discovered registration module: a public static class exposing every discovered
/// handler, plus every discovered upstream module's own registrations (ticket 12), as a container-neutral
/// <c>InterlocutorRegistration</c> list - and the assembly-level attributes that let a downstream project's
/// generator discover this module and its handlers in turn.
/// </summary>
/// <remarks>
/// <para>
/// Every registration is built from <c>typeof(...)</c> tokens resolved at compile time - never from
/// <c>Type.GetType(string)</c> or assembly scanning - which is what keeps this emitted code AOT- and
/// trim-friendly (ADR-0008's stated goal). The registration record itself is
/// <c>Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration</c>, translated into a container's
/// own primitives exactly like a runtime-scanned registration is (see <c>InterlocutorBuilder.AddGeneratedRegistrations</c>) -
/// this generator changes how the list is produced, not how it is consumed.
/// </para>
/// <para>
/// The module lives under <c>Interlocutor.Generated.&lt;SanitizedAssemblyName&gt;</c>, not the bare
/// <c>Interlocutor.Generated</c> namespace - see
/// <c>Interlocutor.DependencyInjection.Abstractions.InterlocutorGeneratedModuleAttribute</c>'s remarks for why
/// an unqualified name would collide across assemblies the moment cross-assembly aggregation is in play.
/// </para>
/// </remarks>
internal static class RegistrationModuleEmitter
{
    /// <summary>The namespace root every generated module lives under, before its per-assembly segment.</summary>
    public const string GeneratedNamespaceRoot = "Interlocutor.Generated";

    /// <summary>The generated registration module's type name.</summary>
    public const string ModuleTypeName = "InterlocutorGeneratedRegistrations";

    /// <summary>
    /// Emits the full source text for the registration module: this compilation's own handlers, concatenated
    /// with every discovered upstream module's own <c>Registrations</c> property (ticket 12).
    /// </summary>
    /// <param name="handlers">Every handler discovered in the compilation.</param>
    /// <param name="assemblyNamespaceSegment">
    /// This compilation's sanitized assembly-name namespace segment - see
    /// <see cref="IdentifierSanitizer.ToNamespaceSegment(string)"/>.
    /// </param>
    /// <param name="externalModules">Every upstream module discovered across the reference graph.</param>
    /// <returns>Compilable C# source text.</returns>
    public static string Emit(
        ImmutableArray<HandlerModel> handlers,
        string assemblyNamespaceSegment,
        ImmutableArray<ExternalModuleInfo> externalModules
    )
    {
        var moduleNamespace = $"{GeneratedNamespaceRoot}.{assemblyNamespaceSegment}";

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator - do not edit by hand. See ADR-0008.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {moduleNamespace}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Compile-time discovered Interlocutor handler registrations for this compilation and every");
        builder.AppendLine("    /// upstream referenced assembly's own generated module (ADR-0008, ticket 12).");
        builder.AppendLine(
            "    /// Pass <see cref=\"Registrations\"/> to <c>InterlocutorBuilder.AddGeneratedRegistrations</c> instead of"
        );
        builder.AppendLine("    /// (or alongside) runtime assembly scanning.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static class {ModuleTypeName}");
        builder.AppendLine("    {");
        builder.AppendLine("        /// <summary>");
        builder.AppendLine("        /// One registration per handler discovered in this compilation, plus every registration");
        builder.AppendLine("        /// exposed by an upstream referenced assembly's own generated module, if any.");
        builder.AppendLine("        /// </summary>");
        builder.AppendLine(
            "        public static global::System.Collections.Generic.IReadOnlyList<global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration> Registrations { get; } = BuildRegistrations();"
        );

        // Always at least two entries: the generated request dispatcher (see RequestDispatchSwitchEmitter) and
        // the generated notification handler order table (see NotificationHandlerOrderEmitter) are registered
        // here unconditionally, even with zero discovered handlers, so a bare compilation still gets a
        // reflection-free (if entirely-unrecognizing) Send(object, ...) dispatch target and a (possibly empty)
        // order table the moment its registrations are passed to AddGeneratedRegistrations. Built as a method
        // body, not a collection initializer, because appending an upstream module's own Registrations
        // (ticket 12) requires a statement (AddRange), not just an expression.
        builder.AppendLine();
        builder.AppendLine(
            "        private static global::System.Collections.Generic.IReadOnlyList<global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration> BuildRegistrations()"
        );
        builder.AppendLine("        {");
        builder.AppendLine(
            "            var registrations = new global::System.Collections.Generic.List<global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration>();"
        );
        builder.AppendLine(
            $"            registrations.Add(new global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration(typeof(global::Interlocutor.Abstractions.Core.IGeneratedRequestDispatcher), typeof(global::{RequestDispatchSwitchEmitter.GeneratedNamespace}.{RequestDispatchSwitchEmitter.DispatcherTypeName}), global::Interlocutor.DependencyInjection.Abstractions.RegistrationLifetime.Singleton, global::Interlocutor.DependencyInjection.Abstractions.RegistrationKind.Dispatcher));"
        );
        builder.AppendLine(
            $"            registrations.Add(new global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration(typeof(global::Interlocutor.Abstractions.Core.IGeneratedNotificationHandlerOrder), typeof(global::{GeneratedNamespaceRoot}.{NotificationHandlerOrderEmitter.TypeName}), global::Interlocutor.DependencyInjection.Abstractions.RegistrationLifetime.Singleton, global::Interlocutor.DependencyInjection.Abstractions.RegistrationKind.Dispatcher));"
        );

        foreach (var handler in handlers)
        {
            builder.AppendLine(
                $"            registrations.Add(new global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration(typeof({handler.ServiceInterfaceName}), typeof({handler.HandlerTypeName}), global::Interlocutor.DependencyInjection.Abstractions.RegistrationLifetime.Scoped, global::Interlocutor.DependencyInjection.Abstractions.RegistrationKind.Handler));"
            );
        }

        foreach (var externalModule in externalModules)
        {
            builder.AppendLine($"            registrations.AddRange({externalModule.QualifiedModuleTypeName}.Registrations);");
        }

        builder.AppendLine("            return registrations;");
        builder.AppendLine("        }");

        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>
    /// Emits every assembly-level attribute identifying this compilation's generated module (as its own
    /// compilation unit - an assembly attribute must precede every other declaration in the file that
    /// contains it, so it cannot share a file with the module class itself): the module attribute itself,
    /// plus one handler attribute per query, command, or bare-command handler (ticket 12).
    /// </summary>
    /// <param name="handlers">Every handler discovered in the compilation.</param>
    /// <param name="assemblyNamespaceSegment">
    /// This compilation's sanitized assembly-name namespace segment - see
    /// <see cref="IdentifierSanitizer.ToNamespaceSegment(string)"/>.
    /// </param>
    /// <returns>Compilable C# source text containing only assembly attributes.</returns>
    public static string EmitAssemblyAttributes(ImmutableArray<HandlerModel> handlers, string assemblyNamespaceSegment)
    {
        var qualifiedModuleTypeName = $"global::{GeneratedNamespaceRoot}.{assemblyNamespaceSegment}.{ModuleTypeName}";

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator - do not edit by hand. See ADR-0008.");
        builder.AppendLine();
        builder.AppendLine(
            $"[assembly: global::Interlocutor.DependencyInjection.Abstractions.InterlocutorGeneratedModuleAttribute(typeof({qualifiedModuleTypeName}))]"
        );

        foreach (var handler in handlers)
        {
            if (handler.Kind == HandlerKind.Notification)
            {
                // Notification handlers never participate in the missing-handler diagnostic - see
                // InterlocutorGeneratedHandlerAttribute's remarks.
                continue;
            }

            var responseTypeArgument = handler.ResponseTypeName is null ? "null" : $"typeof({handler.ResponseTypeName})";
            builder.AppendLine(
                $"[assembly: global::Interlocutor.DependencyInjection.Abstractions.InterlocutorGeneratedHandlerAttribute(typeof({handler.RequestTypeName}), {responseTypeArgument}, global::Interlocutor.DependencyInjection.Abstractions.GeneratedHandlerKind.{handler.Kind})]"
            );
        }

        return builder.ToString();
    }
}
