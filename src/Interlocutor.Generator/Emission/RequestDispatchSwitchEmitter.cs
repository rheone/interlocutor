namespace Interlocutor.Generator.Emission;

using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Interlocutor.Generator.Models;

/// <summary>
/// Emits <c>GeneratedRequestDispatcher</c> - a single <c>IGeneratedRequestDispatcher</c> implementation whose
/// <c>DispatchAsync</c> method is a type switch on the runtime type of an untyped request, replacing the
/// reflection <c>Mediator.SendAsync(object, CancellationToken)</c> otherwise falls back to (ticket 09).
/// </summary>
/// <remarks>
/// <para>
/// Every case in the switch is a concrete, compile-time-known type: one case per request type discovered in
/// the compilation with a matching query/command/void-command handler (dispatching into the corresponding
/// <see cref="DispatchWrapperEmitter"/>-emitted wrapper), and one case per request type discovered with no
/// matching handler (throwing <c>HandlerNotRegisteredException</c>, naming the request and - for a query or
/// command, whose expected handler interface is fully determined by the request's own declared response type
/// - the specific handler interface expected). A request type the generator never saw at all (an
/// unreferenced assembly, or a plain object that is not a request) falls to the switch's <c>default</c>
/// branch, which throws <c>UnsupportedRequestTypeException</c> - the same named exception the reflection path
/// throws for an unrecognized type, never a silent fallthrough.
/// </para>
/// <para>
/// Notification handlers are not part of this switch, for the same reason <see cref="DispatchWrapperEmitter"/>
/// gives them no wrapper - a notification fans out to every registered handler outside the pipeline chain,
/// and <c>ISender.SendAsync(object, CancellationToken)</c> only ever dispatches queries and commands.
/// </para>
/// </remarks>
internal static class RequestDispatchSwitchEmitter
{
    /// <summary>The namespace the generated dispatcher lives under - shared with <see cref="DispatchWrapperEmitter"/> so it can call the wrapper classes emitted there unqualified.</summary>
    public const string GeneratedNamespace = DispatchWrapperEmitter.GeneratedNamespace;

    /// <summary>The generated dispatcher's unqualified type name.</summary>
    public const string DispatcherTypeName = "GeneratedRequestDispatcher";

    /// <summary>
    /// Emits the full source text for <see cref="DispatcherTypeName"/>.
    /// </summary>
    /// <param name="handlers">Every handler discovered in the compilation.</param>
    /// <param name="requests">Every request type discovered in the compilation.</param>
    /// <returns>Compilable C# source text. Valid, with an all-<c>default</c> switch, when nothing was discovered.</returns>
    public static string Emit(ImmutableArray<HandlerModel> handlers, ImmutableArray<RequestModel> requests)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator - do not edit by hand. See ADR-0008.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {GeneratedNamespace}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Compile-time generated type switch dispatching a runtime-typed request (ADR-0008, ticket 13) -"
        );
        builder.AppendLine("    /// the reflection-free replacement for <c>Mediator</c>'s runtime-typed dispatch fallback.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine(
            $"    internal sealed class {DispatcherTypeName} : global::Interlocutor.Abstractions.Core.IGeneratedRequestDispatcher"
        );
        builder.AppendLine("    {");
        builder.AppendLine("        /// <inheritdoc/>");
        builder.AppendLine(
            "        public async global::System.Threading.Tasks.Task<global::System.Runtime.CompilerServices.IUnion> DispatchAsync(object request, global::System.IServiceProvider services, global::System.Threading.CancellationToken ct)"
        );
        builder.AppendLine("        {");
        builder.AppendLine("            switch (request)");
        builder.AppendLine("            {");

        var dispatchable = handlers
            .Where(static h => h.Kind is HandlerKind.Query or HandlerKind.Command or HandlerKind.VoidCommand)
            .GroupBy(static h => h.RequestTypeName)
            .Select(static group => group.First());

        var dispatchedRequestTypes = new HashSet<string>();
        foreach (var handler in dispatchable)
        {
            EmitDispatchCase(builder, handler);
            dispatchedRequestTypes.Add(handler.RequestTypeName);
        }

        foreach (var request in requests.Where(r => !dispatchedRequestTypes.Contains(r.RequestTypeName)))
        {
            EmitUnregisteredCase(builder, request);
        }

        builder.AppendLine("                default:");
        builder.AppendLine(
            "                    throw new global::Interlocutor.Abstractions.Core.UnsupportedRequestTypeException(request.GetType());"
        );
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>Emits a case dispatching a matched request type into its handler's wrapper.</summary>
    private static void EmitDispatchCase(StringBuilder builder, HandlerModel handler)
    {
        var wrapperType = $"global::{GeneratedNamespace}.{DispatchWrapperEmitter.GetWrapperClassName(handler)}";
        builder.AppendLine($"                case {handler.RequestTypeName} typedRequest:");
        builder.AppendLine(
            $"                    return await {wrapperType}.HandleAsync(typedRequest, services, ct).ConfigureAwait(false);"
        );
    }

    /// <summary>
    /// Emits a case for a request type the compilation declares but has no matching handler for - the
    /// generated-dispatch equivalent of the reflection path's explicit registration check, thrown as the same
    /// named <c>HandlerNotRegisteredException</c> rather than falling to the switch's <c>default</c> branch.
    /// </summary>
    private static void EmitUnregisteredCase(StringBuilder builder, RequestModel request)
    {
        var expectedHandlerType = request.Kind switch
        {
            RequestKind.Query =>
                $"typeof(global::Interlocutor.Abstractions.Queries.IQueryHandler<{request.RequestTypeName}, {request.ResponseTypeName}>)",
            RequestKind.Command =>
                $"typeof(global::Interlocutor.Abstractions.Commands.ICommandHandler<{request.RequestTypeName}, {request.ResponseTypeName}>)",

            // A unit command's result type is caller-chosen, not declared on the command - there is no single
            // closed handler interface to name, mirroring the reflection path's own null handlerType here.
            _ => null,
        };

        builder.AppendLine($"                case {request.RequestTypeName}:");
        builder.AppendLine(
            expectedHandlerType is null
                ? $"                    throw new global::Interlocutor.Abstractions.Core.HandlerNotRegisteredException(typeof({request.RequestTypeName}));"
                : $"                    throw new global::Interlocutor.Abstractions.Core.HandlerNotRegisteredException(typeof({request.RequestTypeName}), {expectedHandlerType});"
        );
    }
}
