namespace Interlocutor.Generator;

using System.Collections.Immutable;
using System.Text;

/// <summary>
/// Emits the compile-time discovered registration module: a public static class exposing every discovered
/// handler as a container-neutral <c>InterlocutorRegistration</c>, plus the assembly-level attribute that
/// identifies the module for ticket 12's future cross-assembly aggregation.
/// </summary>
/// <remarks>
/// Every registration is built from <c>typeof(...)</c> tokens resolved at compile time — never from
/// <c>Type.GetType(string)</c> or assembly scanning — which is what keeps this emitted code AOT- and
/// trim-friendly (ADR-0008's stated goal). The registration record itself is
/// <c>Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration</c>, translated into a container's
/// own primitives exactly like a runtime-scanned registration is (see <c>InterlocutorBuilder.AddGeneratedRegistrations</c>) —
/// this generator changes how the list is produced, not how it is consumed.
/// </remarks>
internal static class RegistrationModuleEmitter
{
    /// <summary>The namespace every generated type in this module lives under.</summary>
    public const string GeneratedNamespace = "Interlocutor.Generated";

    /// <summary>The generated registration module's type name.</summary>
    public const string ModuleTypeName = "InterlocutorGeneratedRegistrations";

    /// <summary>
    /// Emits the full source text for the registration module and its identifying assembly attribute.
    /// </summary>
    /// <param name="handlers">Every handler discovered in the compilation.</param>
    /// <returns>Compilable C# source text.</returns>
    public static string Emit(ImmutableArray<HandlerModel> handlers)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator — do not edit by hand. See ADR-0008.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {GeneratedNamespace}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine(
            "    /// Compile-time discovered Interlocutor handler registrations for this compilation (ADR-0008)."
        );
        builder.AppendLine(
            "    /// Pass <see cref=\"Registrations\"/> to <c>InterlocutorBuilder.AddGeneratedRegistrations</c> instead of"
        );
        builder.AppendLine("    /// (or alongside) runtime assembly scanning.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine($"    public static class {ModuleTypeName}");
        builder.AppendLine("    {");
        builder.AppendLine(
            "        /// <summary>One registration per handler contract discovered in this compilation.</summary>"
        );
        builder.AppendLine(
            "        public static global::System.Collections.Generic.IReadOnlyList<global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration> Registrations { get; } ="
        );

        if (handlers.IsEmpty)
        {
            builder.AppendLine(
                "            global::System.Array.Empty<global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration>();"
            );
        }
        else
        {
            builder.AppendLine(
                "            new global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration[]"
            );
            builder.AppendLine("            {");
            foreach (var handler in handlers)
            {
                builder.AppendLine(
                    $"                new global::Interlocutor.DependencyInjection.Abstractions.InterlocutorRegistration(typeof({handler.ServiceInterfaceName}), typeof({handler.HandlerTypeName}), global::Interlocutor.DependencyInjection.Abstractions.RegistrationLifetime.Scoped, global::Interlocutor.DependencyInjection.Abstractions.RegistrationKind.Handler),"
                );
            }

            builder.AppendLine("            };");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    /// <summary>
    /// Emits the assembly-level <c>InterlocutorGeneratedModuleAttribute</c> declaration identifying
    /// <see cref="ModuleTypeName"/>, as its own compilation unit — an assembly attribute must precede every
    /// other declaration in the file that contains it, so it cannot share a file with the module class itself.
    /// </summary>
    /// <returns>Compilable C# source text containing only the assembly attribute.</returns>
    public static string EmitAssemblyAttribute()
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Interlocutor.Generator — do not edit by hand. See ADR-0008.");
        builder.AppendLine();
        builder.AppendLine(
            $"[assembly: global::Interlocutor.DependencyInjection.Abstractions.InterlocutorGeneratedModuleAttribute(typeof(global::{GeneratedNamespace}.{ModuleTypeName}))]"
        );
        return builder.ToString();
    }
}
