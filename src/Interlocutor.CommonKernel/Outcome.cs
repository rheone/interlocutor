/// Represents the outcome of an operation as one of two possible cases.
/// </summary>
/// <typeparam name="T1">
/// The first case type. By convention, the shipped family treats this position as the operation's successful
/// result - but that is a naming convention this family follows, not a meaning the union itself enforces; no
/// case position is privileged over another.
/// </typeparam>
/// <typeparam name="T2">The second case type, by convention the operation's failure result.</typeparam>
/// <remarks>
/// <para>This is a union declaration with two case types: </para>
/// <list type="bullet"><item><description><typeparamref name="T1"/> - the operation completed
/// successfully.</description></item> <item><description><typeparamref name="T2"/> - the operation
/// failed.</description></item> </list>
/// <para>Values of either case type convert implicitly to <see cref="Outcome{T1, T2}"/>,
/// and switch expressions over it are exhaustive without a discard arm. </para>
/// <para><c>Match</c>, <c>Switch</c>, per-case <c>TryGetValue</c>, and <c>ToString</c>
