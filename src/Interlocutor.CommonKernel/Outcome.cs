/// <summary>
/// Represents a fire-and-forget acknowledgment that an operation ran to completion - no case types, no
/// payload, and no success/failure judgment of any kind.
/// </summary>
/// <remarks>
/// <para>
/// Holding an instance of <see cref="Outcome"/> is itself the acknowledgment - there is nothing to inspect on
/// it. Unlike every generic <c>Outcome&lt;T1, ...&gt;</c> arity above, this type is hand-written rather than a
/// compiler-generated <c>union</c> and declares no case types, so it has no <c>Match</c>, <c>Switch</c>, or
/// <c>TryGetValue</c> members - there is nothing to dispatch over. It implements <see cref="IUnion"/> directly,
/// with <see cref="IUnion.Value"/> always <see langword="null"/>, purely to satisfy the response constraint
/// every handler contract and pipeline behavior applies to <c>TResponse</c> - it deliberately does not
/// implement <see cref="IOutcome"/>, unlike the rest of this shipped family.
/// </para>
/// <para>
/// Reserve <see cref="Outcome"/> for a request that is genuinely infallible and opts into none of
/// <c>ICancellableRequest</c>, <c>ITimeoutRequest</c>, or <c>IRateLimitedRequest</c> - none of those cross-cutting pipeline
/// behaviors has a case to construct into a case-less type, so pairing one of them with <see cref="Outcome"/>
/// throws the first time it actually needs to short-circuit, rather than silently doing nothing. An operation
/// that can genuinely fail should declare an explicit <c>Outcome&lt;Success, Failure&gt;</c> (or whichever
/// richer arity matches its real failure modes) instead of reaching for this type.
/// </para>
/// <para>Every instance of <see cref="Outcome"/> compares equal to every other instance, since there is no
/// state to differ on.</para>
/// </remarks>
public readonly record struct Outcome : IUnion
{
    /// <summary>
    /// Gets <see langword="null"/> - <see cref="Outcome"/> carries no payload, so this member exists only to
    /// satisfy <see cref="IUnion"/>, not to be read for information.
    /// </summary>
    /// <value>Always <see langword="null"/>.</value>
    object? IUnion.Value => null;

    /// <summary>
    /// Creates a new <see cref="Outcome"/> acknowledgment. A discoverable alternative to
    /// <see langword="default"/>/<c>new Outcome()</c> - every instance is interchangeable, so this exists purely
    /// so a caller can find a way to obtain one via member-list discovery.
    /// </summary>
    /// <returns>A new <see cref="Outcome"/> instance.</returns>
    public static Outcome Create() => default;

    /// <summary>Returns a fixed, human-readable representation of this outcome.</summary>
    /// <returns>The literal string <c>"Outcome"</c>.</returns>
    public override string ToString() => nameof(Outcome);
}

/// <summary>
/// Represents the outcome of an operation as exactly one case, whose meaning is defined entirely by the
/// caller - not a claim that the operation "succeeded".
/// </summary>
/// <typeparam name="T">
/// The single case type this outcome carries. Nothing about <see cref="Outcome{T}"/> implies this case
/// represents success; it is simply the only case a single-case union can hold.
/// </typeparam>
/// <param name="Value">The value this outcome carries.</param>
/// <remarks>
/// <para>
/// Unlike every generic <c>Outcome&lt;T1, ...&gt;</c> arity above, <see cref="Outcome{T}"/> is a small,
/// hand-written type - not a compiler-generated <c>union</c> and not routed through
/// <see cref="GenerateOutcomeMembersAttribute"/>, since there is only one case: nothing to discriminate.
/// It implements <see cref="IUnion"/> directly - never <see cref="IOutcome"/>, unlike the rest of this shipped
/// family - purely to satisfy the response constraint every handler contract and pipeline behavior applies to
/// <c>TResponse</c>, and hand-declares the same <c>Match</c>/<c>Switch</c>/<c>TryGetValue</c>/<c>ToString</c>/
/// equality member shape every other arity carries, so a caller never has to special-case it.
/// </para>
/// <para>
/// Reserve <see cref="Outcome{T}"/> for an operation with exactly one possible case - so there is nothing to
/// discriminate - that also opts into none of <c>ICancellableRequest</c>, <c>ITimeoutRequest</c>, or
/// <c>IRateLimitedRequest</c>: none of those cross-cutting pipeline behaviors has an alternative case to
/// construct into a single-case type, so pairing one of them with <see cref="Outcome{T}"/> throws the first
/// time it actually needs to short-circuit, rather than silently doing nothing. An operation with a genuine
/// alternative outcome should declare an explicit <c>Outcome&lt;T1, T2&gt;</c> (or whichever richer arity
/// matches its real cases) instead of reaching for this type.
/// </para>
/// </remarks>
public readonly record struct Outcome<T>(T Value) : IUnion
{
    /// <summary>Gets <see cref="Value"/> boxed as an <see cref="object"/>, to satisfy <see cref="IUnion"/>.</summary>
    /// <value>The boxed <see cref="Value"/>.</value>
    object? IUnion.Value => this.Value;

    /// <summary>
    /// Creates a new <see cref="Outcome{T}"/> carrying <paramref name="value"/>. A discoverable alternative to
    /// the positional constructor for the same value.
    /// </summary>
    /// <param name="value">The value the new instance carries.</param>
    /// <returns>A new instance carrying <paramref name="value"/>.</returns>
    public static Outcome<T> Create(T value) => new(value);

    /// <summary>Projects this outcome's value through <paramref name="onValue"/>.</summary>
    /// <typeparam name="TResult">The type <paramref name="onValue"/> projects <see cref="Value"/> to.</typeparam>
    /// <param name="onValue">Invoked with <see cref="Value"/>.</param>
    /// <returns>The result of invoking <paramref name="onValue"/> with <see cref="Value"/>.</returns>
    public TResult Match<TResult>(Func<T, TResult> onValue) => onValue(this.Value);

    /// <summary>Invokes <paramref name="onValue"/> with this outcome's value.</summary>
    /// <param name="onValue">Invoked with <see cref="Value"/>.</param>
    public void Switch(Action<T> onValue) => onValue(this.Value);

    /// <summary>Reads this outcome's value. Retrieval never fails - <see cref="Outcome{T}"/> has exactly one case.</summary>
    /// <param name="value">Set to <see cref="Value"/>.</param>
    /// <returns>Always <see langword="true"/>.</returns>
    public bool TryGetValue(out T value)
    {
        value = this.Value;
        return true;
    }

    /// <summary>Forwards to <see cref="Value"/>'s own <see cref="object.ToString"/> override.</summary>
    /// <returns><c>this.Value?.ToString()</c>, or an empty string when <see cref="Value"/> is <see langword="null"/>.</returns>
    public override string ToString() => this.Value?.ToString() ?? string.Empty;
}

